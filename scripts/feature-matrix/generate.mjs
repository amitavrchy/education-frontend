#!/usr/bin/env node
/** Generates docs/product/FEATURE_MATRIX.md from modules.mjs + status.mjs. */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { modules } from "./modules.mjs";
import { status } from "./status.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../docs/product/FEATURE_MATRIX.md");

const ICON = { done: "✅ Done", partial: "🟨 Partial", todo: "⬜ Todo", blocked: "⛔ Blocked", removed: "🚫 Removed" };
const totals = { done: 0, partial: 0, todo: 0, blocked: 0, removed: 0 };
const esc = (s) => String(s).replaceAll("|", "\\|");

const sections = modules.map((m) => {
  const rows = m.features.map((f, i) => {
    const [title, route] = Array.isArray(f) ? f : [f, m.route];
    const id = `${m.prefix}-${String(i + 1).padStart(2, "0")}`;
    const [st = "todo", tests = "—", note = ""] = status[id] ?? status[`${m.prefix}-*`] ?? [];
    totals[st] += 1;
    return `| ${id} | ${esc(title)}${note ? ` <br><sub>${esc(note)}</sub>` : ""} | \`${esc(route)}\` | ${ICON[st]} | ${esc(tests)} |`;
  });
  const done = rows.filter((r) => r.includes(ICON.done)).length;
  const live = rows.filter((r) => !r.includes(ICON.removed)).length;
  return [
    `## ${m.section} ${m.module} (${done}/${live})`,
    "",
    `- **Roles:** ${m.roles}`,
    `- **Flutter:** ${m.flutter}`,
    `- **Mock data source:** ${m.source}`,
    `- **Loading/error/empty states:** ${m.states}`,
    "",
    "| ID | Feature | Web screen | Status | Tests |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
});

const total = Object.values(totals).reduce((a, b) => a + b, 0);
const md = `# Feature Matrix — education-frontend (Next.js web)

> Generated by \`npm run docs:matrix\` from \`scripts/feature-matrix/\`. Edit the data files, not this file.

Scope of this repository: student web app, public marketing site, admin dashboard, teacher/reviewer,
institution and parent portals. The Flutter student app lives in a **separate repository**; the
"Flutter" line of each module only records where its counterpart is tracked.

**Status rule:** ✅ only when the full user journey works in the mock environment (interactions,
loading/empty/error states, persistence). Screens that exist but miss parts of the journey are 🟨.

| Status | Count |
| --- | --- |
| ✅ Done | ${totals.done} |
| 🟨 Partial | ${totals.partial} |
| ⬜ Todo | ${totals.todo} |
| ⛔ Blocked | ${totals.blocked} |
| 🚫 Removed | ${totals.removed} |
| **Total** | **${total}** |

${sections.join("\n")}`;

writeFileSync(out, md);
console.log(`FEATURE_MATRIX.md written: ${total} features (${totals.done} done, ${totals.partial} partial, ${totals.todo} todo, ${totals.blocked} blocked, ${totals.removed} removed)`);

#!/usr/bin/env node
/** Generates docs/product/SCREEN_INVENTORY.md from src/app route files. */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const app = join(root, "src/app");
const pages = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name === "page.tsx") pages.push(p);
  }
})(app);

const route = (p) => "/" + relative(app, dirname(p)).split("/").filter((s) => !/^\(.*\)$/.test(s)).join("/");
const portal = (r) => (r.split("/")[1] && ["student", "parent", "teacher", "admin"].includes(r.split("/")[1]) ? r.split("/")[1] : /\/(login|register|welcome|verify-otp|forgot-password|reset-password|onboarding|consent|session-expired)/.test(r) ? "auth" : "marketing");
const rows = pages
  .map((p) => {
    const src = readFileSync(p, "utf8");
    const title = src.match(/title:\s*"([^"]+)"/)?.[1] ?? (src.includes("redirect(") ? "(redirect)" : "—");
    const comp = src.match(/<([A-Z][A-Za-z]+)[\s/>]/)?.[1] ?? "—";
    return { r: route(p).replace(/\/$/, "") || "/", title, comp, portal: portal(route(p)) };
  })
  .sort((a, b) => a.portal.localeCompare(b.portal) || a.r.localeCompare(b.r));

const groups = ["marketing", "auth", "student", "parent", "teacher", "admin"];
const md = [
  "# Screen Inventory",
  "",
  "> Generated by `node scripts/screen-inventory.mjs` from `src/app/**/page.tsx`. Do not edit by hand.",
  "",
  `Total routes: **${rows.length}**. Each portal also has shared notifications and settings screens; dialogs/sheets (editors, detail views, wizards) live inside these routes.`,
  "",
  ...groups.flatMap((g) => {
    const list = rows.filter((x) => x.portal === g);
    return [`## ${g[0].toUpperCase() + g.slice(1)} (${list.length})`, "", "| Route | Title | Root component |", "| --- | --- | --- |", ...list.map((x) => `| \`${x.r}\` | ${x.title} | \`${x.comp}\` |`), ""];
  }),
].join("\n");
writeFileSync(join(root, "docs/product/SCREEN_INVENTORY.md"), md);
console.log(`SCREEN_INVENTORY.md written: ${rows.length} routes`);
